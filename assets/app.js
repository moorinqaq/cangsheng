  /* ---------- 声音：皇朝 + 众生炉 ---------- */
  const Sound = {
    ctx: null, master: null, started: false, timer: null,
    init() {
      if (this.ctx) return;
      const AC = window.AudioContext || window.webkitAudioContext;
      if (!AC) return;
      this.ctx = new AC();
      this.master = this.ctx.createGain();
      this.master.gain.value = 0.0001;
      this.master.connect(this.ctx.destination);
    },
    start() {
      this.init();
      if (!this.ctx) return;
      const ctx = this.ctx;
      if (ctx.state === 'suspended') ctx.resume();
      this.master.gain.cancelScheduledValues(ctx.currentTime);
      this.master.gain.linearRampToValueAtTime(0.16, ctx.currentTime + 2.5);

      // 低频 drone：两个略微失谐的锯齿，过低通
      if (!this.drone) {
        const lp = ctx.createBiquadFilter();
        lp.type = 'lowpass'; lp.frequency.value = 240; lp.Q.value = 0.6;
        lp.connect(this.master);
        this.drone = [];
        [55, 82.5, 110].forEach((f, i) => {
          const o = ctx.createOscillator();
          o.type = 'sawtooth';
          o.frequency.value = f;
          const g = ctx.createGain();
          g.gain.value = i === 0 ? 0.5 : 0.18;
          o.connect(g); g.connect(lp); o.start();
          this.drone.push(o);
        });
        // 缓慢起伏
        const lfo = ctx.createOscillator();
        lfo.frequency.value = 0.05;
        const lg = ctx.createGain(); lg.gain.value = 90;
        lfo.connect(lg); lg.connect(lp.frequency); lfo.start();
      }

      if (this.timer) return;
      const bell = () => this.bell();
      const drum = () => this.drum();
      this.bell();
      this.timer = setInterval(() => {
        if (!this.on) return;
        if (Math.random() < 0.7) bell();
        drum();
      }, 3400);
      this.started = true;
    },
    stop() {
      if (!this.ctx) return;
      this.master.gain.cancelScheduledValues(this.ctx.currentTime);
      this.master.gain.linearRampToValueAtTime(0.0001, this.ctx.currentTime + 1.2);
    },
    bell() {
      const ctx = this.ctx;
      const t = ctx.currentTime;
      const base = [196, 261.6, 392][Math.floor(Math.random() * 3)];
      [1, 2.01, 3.02].forEach((m, i) => {
        const o = ctx.createOscillator();
        o.type = 'triangle';
        o.frequency.value = base * m;
        const g = ctx.createGain();
        g.gain.setValueAtTime(0, t);
        g.gain.linearRampToValueAtTime(0.05 / (i + 1), t + 0.02);
        g.gain.exponentialRampToValueAtTime(0.0001, t + 6 + i);
        o.connect(g); g.connect(this.master);
        o.start(t); o.stop(t + 7 + i);
      });
    },
    drum() {
      const ctx = this.ctx;
      const t = ctx.currentTime;
      const o = ctx.createOscillator();
      o.type = 'sine';
      o.frequency.setValueAtTime(78, t);
      o.frequency.exponentialRampToValueAtTime(38, t + 0.35);
      const g = ctx.createGain();
      g.gain.setValueAtTime(0.22, t);
      g.gain.exponentialRampToValueAtTime(0.0001, t + 0.7);
      o.connect(g); g.connect(this.master);
      o.start(t); o.stop(t + 0.8);
    }
  };

