  function radarSVG(vals, color) {
    const cx = 150, cy = 142, R = 92, n = 6;
    const pt = (i, r) => {
      const a = -Math.PI / 2 + i * 2 * Math.PI / n;
      return [cx + Math.cos(a) * r, cy + Math.sin(a) * r];
    };
    let rings = '';
    for (let k = 1; k <= 5; k++) {
      const pts = [];
      for (let i = 0; i < n; i++) { const [x, y] = pt(i, R * k / 5); pts.push(x.toFixed(1) + ',' + y.toFixed(1)); }
      rings += `<polygon points="${pts.join(' ')}" fill="none" stroke="#c8a24a" stroke-opacity="${k === 5 ? .3 : .11}"/>`;
    }
    let axes = '';
    for (let i = 0; i < n; i++) {
      const [x, y] = pt(i, R);
      axes += `<line x1="${cx}" y1="${cy}" x2="${x}" y2="${y}" stroke="#c8a24a" stroke-opacity=".15"/>`;
    }
    let labels = '';
    DIMS.forEach((d, i) => {
      const [x, y] = pt(i, R + 24);
      labels += `<text x="${x}" y="${y + 3}" text-anchor="middle">${d}</text>`;
    });
    const poly = vals.map((v, i) => { const [x, y] = pt(i, R * v / 5); return x.toFixed(1) + ',' + y.toFixed(1); }).join(' ');
    const dots = vals.map((v, i) => {
      const [x, y] = pt(i, R * v / 5);
      return `<circle cx="${x.toFixed(1)}" cy="${y.toFixed(1)}" r="2.6" fill="${color}"/>`;
    }).join('');
    return `<svg class="radar" viewBox="0 0 300 300" role="img" aria-label="六维图">
      ${rings}${axes}
      <polygon points="${poly}" fill="${color}" fill-opacity=".2" stroke="${color}" stroke-opacity=".85" stroke-width="1.5"/>
      ${dots}${labels}</svg>`;
  }

